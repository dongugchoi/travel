export function t (text, params) {
  let out = i18n.lang === 'ja' && JA[text] !== undefined ? JA[text] : text
  if (params) {
    Object.keys(params).forEach((k) => { out = out.split(`{${k}}`).join(params[k]) })
  }
  return out
}

export function setLang (lang) {
  if (!LANGS.some(l => l.value === lang)) return
  i18n.lang = lang
  try { localStorage.setItem('travel-lang', lang) } catch (e) {}
  if (typeof document !== 'undefined') document.documentElement.lang = lang
}

// 템플릿에서 $t('...'), $lang 로 사용
// (개발 서버가 파일을 다시 읽어도 오류 나지 않게 configurable)
Vue.prototype.$t = t
Object.defineProperty(Vue.prototype, '$lang', { get: () => i18n.lang, configurable: true })

export default ({ store }) => {
  // 직접 입력한 글자(일정 이름·장소 등): 일본어일 때 저장된 번역이 있으면 그걸 보여줌
  Vue.prototype.$tx = (text) => {
    if (i18n.lang !== 'ja' || !text) return text
    const tr = store.state.trip && store.state.trip.tr
    return (tr && tr[String(text).trim()]) || text
  }

  if (process.client) {
    // 서버에서 그린 화면(한국어)과 어긋나지 않게, 화면이 준비된 뒤에 저장된 언어로 바꿈
    window.onNuxtReady(() => {
      try {
        const saved = localStorage.getItem('travel-lang')
        if (saved) setLang(saved)
      } catch (e) {}
    })
  }
}
